#!/usr/bin/env node
// Static, read-only build of the web app for GitLab Pages / GitHub Pages: the landing (the recorded agent
// run played back, both exported packs verified in the browser) and the offline /verify page. Neither needs
// a server. The recorder dashboard and its API are local-only by design (middleware.ts refuses non-loopback
// hosts), so they are left out of this build rather than published.
//
// It copies apps/web into a scratch folder without app/api, app/recorder and middleware.ts, runs
// `next build` there with output: "export", and moves the exported site to --out.
//
//   node scripts/build-pages.mjs [--out public] [--base-path /blackbox-receipts]
//
// --base-path (or PAGES_BASE_PATH) is the URL path the site is served under: "/<project>" for
// <user>.gitlab.io/<project>/ or <user>.github.io/<project>/, and "" for a root or unique domain.
// Build the workspace packages first: pnpm --filter "@blackbox/web^..." build
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const web = join(root, 'apps/web');
const stage = join(web, '.pages-build');

function arg(name, fallback) {
  const index = process.argv.indexOf(`--${name}`);
  if (index === -1) return fallback;
  const value = process.argv[index + 1];
  if (value === undefined || value.startsWith('--')) throw new Error(`--${name} needs a value`);
  return value;
}

function fail(message) {
  console.error(`build-pages: ${message}`);
  process.exit(1);
}

const out = resolve(root, arg('out', 'public'));
let basePath = arg('base-path', process.env.PAGES_BASE_PATH ?? '').trim().replace(/\/+$/, '');
if (basePath && !basePath.startsWith('/')) basePath = `/${basePath}`;
if (basePath && !/^\/[A-Za-z0-9._~\-/]+$/.test(basePath)) fail(`base path "${basePath}" has characters a URL path cannot carry as-is`);
// --out is deleted and replaced, so it must be a folder of its own inside the repo (public/ for GitLab Pages).
const outRel = relative(root, out);
const PROTECTED = new Set(['apps', 'packages', 'receipts', 'scripts', 'test', 'examples', 'docs', 'release', 'node_modules', '.git', '.loom']);
if (!outRel || outRel.startsWith('..') || PROTECTED.has(outRel.split(/[\\/]/)[0])) {
  fail(`refusing to replace ${out}: pick an output folder of its own inside the repo, such as public/`);
}

const verifyDist = join(root, 'packages/verify/dist/index.js');
if (!existsSync(verifyDist)) fail('packages/verify/dist is missing. Build the packages first: pnpm --filter "@blackbox/web^..." build');

// 1. Stage apps/web without the local-only parts.
rmSync(stage, { recursive: true, force: true });
mkdirSync(stage, { recursive: true });
const LOCAL_ONLY = new Set(['api', 'recorder']);
cpSync(join(web, 'app'), join(stage, 'app'), {
  recursive: true,
  filter: (source) => {
    const parts = relative(join(web, 'app'), source).split(/[\\/]/);
    return !LOCAL_ONLY.has(parts[0]);
  },
});
cpSync(join(web, 'tsconfig.json'), join(stage, 'tsconfig.json'));
writeFileSync(join(stage, 'next.config.mjs'), `// Generated by scripts/build-pages.mjs. Static export of the landing and /verify only.
export default {
  output: 'export',
  trailingSlash: true,
  basePath: ${JSON.stringify(basePath)},
  images: { unoptimized: true },
  transpilePackages: ['@blackbox/verify', '@blackbox/receipts', '@blackbox/proxy'],
};
`);

// 2. Build. `next` and the workspace packages resolve from apps/web/node_modules (the stage sits inside it).
const require = createRequire(join(web, 'package.json'));
const nextBin = join(dirname(require.resolve('next/package.json')), 'dist/bin/next');
const result = spawnSync(process.execPath, [nextBin, 'build'], {
  cwd: stage,
  stdio: 'inherit',
  env: {
    ...process.env,
    NEXT_TELEMETRY_DISABLED: '1',
    NEXT_PUBLIC_BLACKBOX_STATIC: '1',
    NEXT_PUBLIC_BASE_PATH: basePath,
  },
});
if (result.status !== 0) {
  rmSync(stage, { recursive: true, force: true });
  fail(`next build failed (exit ${result.status ?? result.signal})`);
}

// 3. Publish the export.
const exported = join(stage, 'out');
for (const page of ['index.html', 'verify/index.html']) {
  if (!existsSync(join(exported, page))) fail(`the export has no ${page}`);
}
rmSync(out, { recursive: true, force: true });
mkdirSync(dirname(out), { recursive: true });
renameSync(exported, out);
writeFileSync(join(out, '.nojekyll'), '');
rmSync(stage, { recursive: true, force: true });

const files = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((entry) => (entry.isDirectory() ? files(join(dir, entry.name)) : [entry.name]));
console.log(`build-pages: ${files(out).length} files in ${relative(root, out) || '.'} for base path "${basePath || '/'}" (landing + /verify; recorder and API left out)`);
