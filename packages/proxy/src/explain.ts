// Turns a recorded session into step-cited markdown: every line names the receipt it comes from, and
// raw arguments are shown only when they open that receipt's signed argsHash.
import { argsMatch, evaluateStep, type Receipt, type SecretPolicy, type Witness } from '@blackbox/receipts';

export type ExplainInput = {
  receipts: Receipt[];
  witnesses: Witness[];
  policy: SecretPolicy;
  /** The prover's PASS/FAIL line, verbatim. */
  verdict: string;
  chain: { valid: boolean; brokenAt: number | null; reason: string | null };
  root: string;
  seal: string;
};

const code = (text: string) => `\`${text.replaceAll('`', "'")}\``;
const clip = (text: string, size = 90) => (text.length > size ? `${text.slice(0, size - 1)}…` : text);

/** One-line description of what a call asked for, from its raw arguments. */
export function describeCall(tool: string, args: unknown): string {
  const input = (args ?? {}) as Record<string, unknown>;
  if (tool === 'read_file' && typeof input.path === 'string') return `read_file ${input.path}`;
  if (tool === 'write_file' && typeof input.path === 'string') return `write_file ${input.path}`;
  if (tool === 'git') return clip(['git', String(input.action ?? '?'), ...((Array.isArray(input.args) ? input.args : []) as string[])].join(' '));
  if (tool === 'shell' && typeof input.command === 'string') return clip(`shell ${input.command}`);
  return clip(`${tool} ${JSON.stringify(args)}`);
}

export function explainSession({ receipts, witnesses, policy, verdict, chain, root, seal }: ExplainInput): string {
  const lines: string[] = [];
  const sessionId = receipts[0]?.sessionId ?? 'empty session';
  lines.push(`# Session ${sessionId}`, '');
  lines.push(`**Verdict:** ${code(verdict)}`, '');
  lines.push(`- Chain: ${chain.valid ? `${receipts.length} receipts, every signature and link verifies` : `broken at step ${chain.brokenAt}: ${chain.reason}`}`);
  lines.push(`- Merkle root: ${code(root)}`);
  lines.push(`- Seal: ${seal}`);
  lines.push(`- Policy: ${code(policy.id)}`, '');
  if (!receipts.length) { lines.push('No tool calls were recorded, so there is nothing to explain.'); return `${lines.join('\n')}\n`; }
  lines.push('## Steps', '');
  const violations: { step: number; reason: string; receipt: Receipt; described: string }[] = [];
  for (const receipt of receipts) {
    const witness = witnesses.find((item) => item.sessionId === receipt.sessionId && item.step === receipt.step);
    const opened = witness && argsMatch(receipt.argsHash, witness.args, witness.salt);
    const described = opened ? describeCall(receipt.tool, witness.args) : `${receipt.tool} ${receipt.paths.join(' ')}`.trim();
    const outcome = receipt.outcome === 'denied' ? '**DENIED**' : receipt.outcome === 'error' ? 'error' : receipt.outcome === 'ok' ? 'ok' : 'recorded';
    const detail = opened && witness.detail ? ` — ${witness.detail}` : '';
    const time = receipt.timestamp.slice(11, 19);
    const note = !witness ? ' (raw arguments missing; shown from the receipt\'s paths)' : !opened ? ' (stored arguments do NOT match the signed argsHash; shown from the receipt\'s paths)' : '';
    lines.push(`- **step ${receipt.step}** ${time} ${code(described)} → ${outcome}${detail}${note} · receipt ${code(receipt.hash.slice(0, 12))}`);
    const reason = opened ? evaluateStep(receipt, witness.args, policy) : null;
    if (reason) violations.push({ step: receipt.step, reason, receipt, described });
  }
  lines.push('', '## Why', '');
  if (!chain.valid) lines.push(`The log was changed after signing: step ${chain.brokenAt} fails verification (${chain.reason}). Nothing from step ${chain.brokenAt} on can be trusted.`);
  if (!violations.length && chain.valid) lines.push(`No step touches a path or argument that ${code(policy.id)} forbids.`);
  for (const { step, reason, receipt, described } of violations) {
    const before = receipts.filter((item) => item.step < step).slice(-2).map((item) => {
      const witness = witnesses.find((entry) => entry.sessionId === item.sessionId && entry.step === item.step);
      return `step ${item.step} ${code(witness && argsMatch(item.argsHash, witness.args, witness.salt) ? describeCall(item.tool, witness.args) : item.tool)}`;
    });
    const ran = receipt.outcome === 'denied' ? 'The proxy refused it before it ran, so the agent never received the contents; the attempt itself is what the proof reports.' : receipt.outcome === 'ok' ? 'The call ran and its result went back to the agent.' : receipt.outcome === 'error' ? 'The call failed.' : '';
    lines.push(`- **step ${step}** ${code(described)} violates ${code(policy.id)}: ${reason}.${ran ? ` ${ran}` : ''}${before.length ? ` It came right after ${before.join(' and ')}.` : ''}`);
  }
  lines.push('', '_Generated by `blackbox-receipts explain` from the signed receipts and the private witness. Each argument shown was checked against its receipt\'s argsHash._');
  return `${lines.join('\n')}\n`;
}
